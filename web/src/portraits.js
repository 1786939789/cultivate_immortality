export function portraitFor(person) {
  if (!person?.name) return "";
  return encodePercentFilename(portraitMap[person.name] || "");
}

export function portraitMapEntries() {
  return Object.entries(portraitMap).map(([name, src]) => [name, encodePercentFilename(src)]);
}

function encodePercentFilename(src) {
  return src.replaceAll("%", "%25");
}
